"""MOCK: построение биометрических шаблонов.

=== Что здесь заглушка ===
Вместо ArcFace шаблон строится детерминированно из `employee_id`. Пара «похожих»
сотрудников собирается точной ортогонализацией, поэтому косинус между их
шаблонами равен заданному значению ровно, а не приблизительно — на этом держатся
детерминированные тесты порогов.

=== Чем заменяется в целевой архитектуре ===
ArcFace/AdaFace, 512-d, ONNX Runtime FP16 на edge-GPU, поверх выровненного
кропа 112x112 (docs/ml.md).

=== Почему это отдельный модуль ===
Шаблон сотрудника обязан быть **один на всю систему**: и тот, что лежит в
хранилище, и тот, от которого моделируется проба с камеры. Пока эта логика была
продублирована в двух местах, проба для сотрудника с близнецом строилась от
другого базового вектора, и match_score молча занижался. См. AI_USAGE.md.
"""

from __future__ import annotations

from .vectors import Vector, blend, unit_random


def enrollment_template(person_id: str) -> Vector:
    """Базовый шаблон — то, что записывается при энролменте сотрудника."""
    return unit_random(f"person::{person_id}")


def similar_template(person_id: str, similar_to: str, similarity: float) -> Vector:
    """Шаблон человека, биометрически близкого к другому (близнецы, родственники).

    Нужен, чтобы в демо был честный трудный случай с двумя близкими кандидатами,
    а не искусственно подставленный малый margin.
    """
    return blend(enrollment_template(similar_to), f"person::{person_id}", similarity)
